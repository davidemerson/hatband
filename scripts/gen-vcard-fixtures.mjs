#!/usr/bin/env node
// Writes HatbandTests/SiteVCardFixtures.swift: the vCard hatband.link builds
// (`cardVCard` in site/src/hb1.js) for every vector in spec/vectors/cards.json,
// as Swift string literals. LinksTests pins the app's vCard to these bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { cardFromMap, cardVCard, hb1DecodeURL } = await import(pathToFileURL(join(root, 'site/src/hb1.js')).href);
const vectors = JSON.parse(readFileSync(join(root, 'spec/vectors/cards.json'), 'utf8')).vectors;

/** A Swift string literal: printable ASCII as is, everything else as an escape. */
function swiftLiteral(text) {
  let out = '"';
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\n') out += '\\n';
    else if (cp >= 0x20 && cp <= 0x7e) out += ch;
    else out += '\\u{' + cp.toString(16).toUpperCase() + '}';
  }
  return out + '"';
}

let swift = '// Generated by scripts/gen-vcard-fixtures.mjs from site/src/hb1.js `cardVCard`\n';
swift += '// over spec/vectors/cards.json. Regenerate rather than edit.\n';
swift += 'import Foundation\n\n';
swift += '/// What hatband.link\'s "Add to contacts" produces for each vector.\n';
swift += 'nonisolated enum SiteVCardFixtures {\n';
swift += '    static let text: [String: String] = [\n';
for (const v of vectors) {
  const card = cardFromMap(hb1DecodeURL(v.url));
  swift += '        ' + swiftLiteral(v.name) + ':\n            ' + swiftLiteral(cardVCard(card)) + ',\n';
}
swift += '    ]\n}\n';
const out = join(root, 'HatbandTests/SiteVCardFixtures.swift');
writeFileSync(out, swift);
console.log('wrote ' + out + ' (' + vectors.length + ' vectors)');
